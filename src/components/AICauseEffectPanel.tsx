import React, { useState } from 'react';
import { RoadSegmentProfile } from '../types/accident';
import { CAUSAL_CHAINS } from '../data/digitalTwinCityData';
import { ArrowDown, AlertTriangle, Sparkles, Activity, Layers, Info } from 'lucide-react';
import { tacticalAudio } from '../services/tacticalAudio';

interface AICauseEffectPanelProps {
  selectedRoad: RoadSegmentProfile;
}

export const AICauseEffectPanel: React.FC<AICauseEffectPanelProps> = ({ selectedRoad }) => {
  const [activeStepId, setActiveStepId] = useState<string | null>(null);

  const chain = CAUSAL_CHAINS[selectedRoad.id] || CAUSAL_CHAINS['default'];

  return (
    <div className="absolute top-20 right-6 z-20 w-84 bg-[#0F172A]/90 backdrop-blur-md border border-slate-800 rounded-2xl p-4 shadow-2xl text-slate-200 font-mono text-xs space-y-4 max-h-[82vh] overflow-y-auto">
      
      {/* Header */}
      <div className="pb-2 border-b border-slate-800">
        <div className="flex items-center gap-2">
          <Sparkles className="w-3.5 h-3.5 text-violet-400" />
          <span className="font-extrabold text-white uppercase tracking-wider text-[11px]">
            AI CAUSE &rarr; EFFECT CHAIN
          </span>
        </div>
        <p className="text-[10px] text-slate-400 font-sans mt-0.5">
          Why is <strong>{selectedRoad.id} ({selectedRoad.name})</strong> becoming dangerous?
        </p>
      </div>

      {/* Animated Causal Flow Nodes */}
      <div className="space-y-2 py-1">
        {chain.map((node, idx) => {
          const isSelected = activeStepId === node.id;
          const isLast = idx === chain.length - 1;

          return (
            <React.Fragment key={node.id}>
              {/* Node Card */}
              <div 
                onClick={() => {
                  tacticalAudio.playTick();
                  setActiveStepId(isSelected ? null : node.id);
                }}
                className={`p-3 rounded-xl border transition-all cursor-pointer select-none ${
                  isLast
                    ? 'bg-red-950/40 border-red-800/80 hover:bg-red-950/60 shadow-md'
                    : isSelected
                    ? 'bg-violet-950/50 border-violet-500 shadow-md ring-1 ring-violet-500'
                    : 'bg-slate-900/80 border-slate-800 hover:border-slate-700'
                }`}
              >
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    <span className={`w-5 h-5 rounded-full flex items-center justify-center text-[10px] font-bold ${
                      isLast ? 'bg-red-600 text-white' : 'bg-slate-800 text-violet-300'
                    }`}>
                      {idx + 1}
                    </span>
                    <span className={`font-bold tracking-tight text-[11px] ${
                      isLast ? 'text-red-400' : 'text-slate-100'
                    }`}>
                      {node.label}
                    </span>
                  </div>

                  <span className={`font-mono text-[10px] font-bold px-1.5 py-0.5 rounded ${
                    isLast ? 'bg-red-900 text-red-200' : 'bg-slate-800 text-violet-400'
                  }`}>
                    {node.value}
                  </span>
                </div>

                <p className="text-[11px] font-sans text-slate-400 mt-1.5 leading-relaxed pl-7">
                  {node.description}
                </p>

                {isSelected && (
                  <div className="mt-2 pt-2 border-t border-slate-800 text-[10px] text-violet-300 font-mono flex justify-between pl-7">
                    <span>SHAP Factor Impact:</span>
                    <strong>+{node.impactScore} pts risk shift</strong>
                  </div>
                )}
              </div>

              {/* Animated Connector Arrow */}
              {!isLast && (
                <div className="flex flex-col items-center justify-center my-0.5 text-slate-600">
                  <div className="w-0.5 h-3 bg-gradient-to-b from-slate-700 to-violet-500/60"></div>
                  <ArrowDown className="w-3.5 h-3.5 text-violet-400 animate-bounce" />
                </div>
              )}
            </React.Fragment>
          );
        })}
      </div>

      {/* Causal Summary */}
      <div className="pt-2 border-t border-slate-800 text-[10px] text-slate-400 font-sans italic flex items-center gap-1.5">
        <Info className="w-3.5 h-3.5 shrink-0 text-slate-500" />
        <span>Multivariate causal graph generated by neural causal attribution model; weights validated against historical crash database.</span>
      </div>

    </div>
  );
};
